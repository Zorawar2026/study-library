  const cols = ["Very Low", "Low", "Moderate", "High", "Very High"];
  // r = high (purple on the slide), y = medium (yellow), g = low (teal)
  const z = ["gyrrr", "gyrrr", "gyyyr", "ggggy", "ggggg"];
  const fill = { r: "#7b3fa0", y: "#e0b43a", g: "#2a9d8f" };
